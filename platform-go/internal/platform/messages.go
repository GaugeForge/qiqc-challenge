func englishMessage(message string) string {
	if translated, ok := englishMessages[message]; ok {
		return translated
	}
	for _, char := range message {
		if unicode.Is(unicode.Han, char) {
			return "The request could not be completed. Check the current status or contact staff."
		}
	}
	return message
}
