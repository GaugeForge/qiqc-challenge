import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../web/app.js',import.meta.url),'utf8');
const kindRadios=[{value:'infra'},{value:'public'},{value:'full'}];
const context=vm.createContext({document:{querySelectorAll:()=>kindRadios,querySelector:()=>null}});
vm.runInContext(source.slice(source.indexOf('function evaluationAvailability('),source.indexOf('function updateRunHint(')),context);
const available={scientific_task_set:{configured:true,infra_ready:true,full_ready:true,public_ready:false}};
assert.equal(context.evaluationAvailability(available,'scientific','infra'),'');
assert.equal(context.evaluationAvailability(available,'scientific','full'),'');
assert.match(context.evaluationAvailability(available,'scientific','public'),/all five tasks/);
assert.match(context.evaluationAvailability({},'scientific','infra'),/not configured/);
assert.match(context.evaluationAvailability(available,'scientific-smoke','full'),/infrastructure task only/);
assert.equal(context.evaluationAvailability(available,'simulated','public'),'');
assert.equal(context.evaluationAvailability({scientific_task_set:{...available.scientific_task_set,public_ready:true}},'scientific','public'),'');
const normal=source.slice(source.indexOf('function submitPage('),source.indexOf('function leaderboardPage('));
assert(!normal.includes('manual_required'));
assert(!normal.includes('等待管理员复核'));
assert(/v.status\s*===\s*['"]approved['"]/.test(normal));
assert(/pending_review:\s*\[\s*['"]Under review['"]/.test(source));
const elements={
 '#kind-select':{value:'public',options:[{value:'infra'},{value:'public'},{value:'full'}]},
 '#run-hint':{}, '#upload-button':{}, '#zip-file':{}, '#drop-zone':{classList:{toggle(){}}}
};
context.elements=elements;
context.selectedKind=()=>elements['#kind-select'].value;
vm.runInContext("const $=selector=>elements[selector];const totals={full:39,public:5,infra:3};let platformConfig="+JSON.stringify({...available,phase:{allowed_kinds:['infra','public','full'],upload_allowed:true}})+";let batches=[],submissionIntents=[],uploadBusy=false,user={quotas:{public:3,infra:10,full:1}};function phaseNotice(){return 'Admission is open';}"+source.slice(source.indexOf('function updateRunHint('),source.indexOf('function renderSubmissionStatus(')),context);
context.updateRunHint();
assert.equal(elements['#upload-button'].disabled,true);
assert.equal(elements['#kind-select'].value,'public');
assert.match(elements['#run-hint'].textContent,/unavailable/);
vm.runInContext("platformConfig.scientific_task_set.public_ready=true",context);
context.updateRunHint();
assert.equal(elements['#upload-button'].disabled,false);
assert.match(elements['#run-hint'].textContent,/5 tasks/);
vm.runInContext("user.quotas.public=0",context);context.updateRunHint();
assert.equal(elements['#upload-button'].disabled,true);
assert.match(elements['#run-hint'].textContent,/No attempts/);
vm.runInContext("user.quotas.public=3;batches=[{status:'attention'}]",context);context.updateRunHint();
assert.equal(elements['#upload-button'].disabled,true);
assert.match(elements['#run-hint'].textContent,/resolved by staff/);
vm.runInContext("batches=[];submissionIntents=[{state:'reviewing'}]",context);context.updateRunHint();
assert.equal(elements['#upload-button'].disabled,true);
assert.match(elements['#run-hint'].textContent,/under review/);
vm.runInContext("submissionIntents=[];uploadBusy=true",context);context.updateRunHint();
assert(kindRadios.every(r=>r.disabled));
assert.equal(elements['#zip-file'].disabled,true);
vm.runInContext("uploadBusy=false;platformConfig.phase={allowed_kinds:[],upload_allowed:false}",context);context.updateRunHint();
assert.equal(elements['#upload-button'].disabled,true);
assert.match(elements['#run-hint'].textContent,/closed|not open now/);
console.log('Automatic upload admission: phase, task readiness, quotas, unresolved batches, pending review and in-flight controls passed');
